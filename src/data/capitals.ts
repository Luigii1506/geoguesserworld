/** URL oficial de Google Maps que abre el panorama de Street View más cercano. */
export function streetViewUrl(lat: number, lng: number): string {
  return `https://www.google.com/maps/@?api=1&map_action=pano&viewpoint=${lat},${lng}`
}

export function countryStreetView(code: string): { name: string; url: string } | null {
  const city = REF_CITIES[code]
  if (!city) return null
  return { name: city.name, url: streetViewUrl(city.lat, city.lng) }
}
